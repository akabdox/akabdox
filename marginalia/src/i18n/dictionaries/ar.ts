// Arabic counts: one, two, few (3 to 10), many (11 to 99), other.
const rules = new Intl.PluralRules('ar')
function count(n: number, forms: { zero: string; one: string; two: string; few: string; many: string; other: string }) {
  const form = n === 0 ? 'zero' : (rules.select(n) as keyof typeof forms)
  return forms[form].replace('{n}', String(n))
}

